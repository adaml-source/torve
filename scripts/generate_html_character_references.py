"""Generate portable Kotlin data for the standardized HTML named references.

Uses Python's standard-library table, with no runtime dependency or network
access. Require a semicolon so ordinary ampersands in titles stay unchanged.
"""

import html.entities
from pathlib import Path


def main():
    entries = [
        f"{name[:-1]}={','.join(f'{ord(character):X}' for character in text)}"
        for name, text in sorted(html.entities.html5.items())
        if name.endswith(";")
    ]
    lines = ["        " + " ".join(entries[index:index + 8]) for index in range(0, len(entries), 8)]
    data = "\n".join(lines)
    source = '''package com.torve.util

// Generated by scripts/generate_html_character_references.py.
// Standard HTML character-reference names and Unicode scalar values:
// https://html.spec.whatwg.org/multipage/named-characters.html
internal object HtmlCharacterReferences {
    val values: Map<String, String> by lazy {
        DATA.trimIndent().lineSequence().flatMap { it.split(' ').asSequence() }
            .filter { it.isNotBlank() }
            .associate { entry ->
                entry.substringBefore('=') to entry.substringAfter('=').split(',')
                    .joinToString("") { unicodeScalarText(it.toInt(16)).orEmpty() }
            }
    }

    private const val DATA = """
''' + data + '''
    """
}
'''
    target = Path(__file__).resolve().parents[1] / "shared/src/commonMain/kotlin/com/torve/util/HtmlCharacterReferences.kt"
    target.write_text(source, encoding="utf-8", newline="\n")
    print(f"Generated {len(entries)} named references.")


if __name__ == "__main__":
    main()

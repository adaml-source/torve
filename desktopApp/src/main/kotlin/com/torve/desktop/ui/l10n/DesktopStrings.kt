/**
 * Central desktop string catalog.
 *
 * Keys are the English source string; per-locale maps override translations.
 * Missing keys fall back to the English source, so partially translated locales
 * still render sensibly.
 *
 * Usage from a Composable:
 *   val s = LocalDesktopStrings.current
 *   Text(s["Home"])
 *
 * Wire the locale in V2App by wrapping content in
 *   CompositionLocalProvider(LocalDesktopStrings provides desktopStringsFor(lang))
 */
class DesktopStrings internal constructor(
    private val translations: Map<String, String>,
) {
    operator fun get(key: String): String = translations[key] ?: key
}

val LocalDesktopStrings = compositionLocalOf { DesktopStrings(emptyMap()) }

@Composable
@ReadOnlyComposable
fun ds(key: String): String = LocalDesktopStrings.current[key]

fun desktopStringsFor(language: AppLanguage): DesktopStrings =
    DesktopStrings(translationsFor(language))

private fun translationsFor(language: AppLanguage): Map<String, String> = when (language) {
    AppLanguage.ENGLISH -> emptyMap()
    AppLanguage.GERMAN -> GERMAN
    AppLanguage.SPANISH -> SPANISH
    AppLanguage.FRENCH -> FRENCH
    AppLanguage.ITALIAN -> ITALIAN
    AppLanguage.PORTUGUESE -> PORTUGUESE
    AppLanguage.TURKISH -> TURKISH
}

